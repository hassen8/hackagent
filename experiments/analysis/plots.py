def _load_taxonomy(source: Mapping[str, Any] | str | Path | None) -> dict[str, Any]:
    manifest: Mapping[str, Any] | None = None
    if isinstance(source, Mapping):
        manifest = source
    else:
        path = (
            Path(source).expanduser() if source is not None else DEFAULT_GOAL_MANIFEST
        )
        if path.exists():
            try:
                value = json.loads(path.read_text(encoding="utf-8"))
                if isinstance(value, Mapping):
                    manifest = value
            except (OSError, json.JSONDecodeError):
                manifest = None
    categories: list[str] = []
    category_labels: dict[str, str] = {}
    subcategories: list[tuple[str, str]] = []
    subcategory_labels: dict[str, str] = {}
    batch_to_taxonomy: dict[str, tuple[str, str]] = {}
    if manifest is not None:
        for category in manifest.get("selected_categories", []):
            category_text = _text(category)
            if category_text and category_text not in categories:
                categories.append(category_text)
        for goal in manifest.get("goals", []):
            if not isinstance(goal, Mapping):
                continue
            category = _text(goal.get("category_id"))
            subcategory = _text(goal.get("subcategory_id"))
            if category and category not in categories:
                categories.append(category)
            if (
                category
                and subcategory
                and (category, subcategory) not in subcategories
            ):
                subcategories.append((category, subcategory))
            if category:
                category_labels.setdefault(
                    category, _text(goal.get("category_label"), category)
                )
            if subcategory:
                subcategory_labels.setdefault(
                    subcategory, _text(goal.get("subcategory_label"), subcategory)
                )
            batch = _text(goal.get("goal_batch_id"))
            if batch and category and subcategory:
                batch_to_taxonomy[batch] = (category, subcategory)
        for batch in manifest.get("batches", []):
            if not isinstance(batch, Mapping):
                continue
            category = _text(batch.get("category_id"))
            subcategory = _text(batch.get("subcategory_id"))
            batch_id = _text(batch.get("goal_batch_id"))
            if category and category not in categories:
                categories.append(category)
            if (
                category
                and subcategory
                and (category, subcategory) not in subcategories
            ):
                subcategories.append((category, subcategory))
            if batch_id and category and subcategory:
                batch_to_taxonomy[batch_id] = (category, subcategory)
    return {
        "categories": categories or list(CATEGORIES),
        "category_labels": category_labels,
        "subcategories": subcategories,
        "subcategory_labels": subcategory_labels,
        "batch_to_taxonomy": batch_to_taxonomy,
        "goals_per_subcategory": (
            manifest.get("goals_per_subcategory") if manifest is not None else None
        ),
        "manifest": manifest,
    }


def _load_taxonomy_with_findings(
    source: Mapping[str, Any] | str | Path | None,
    findings: list[dict[str, Any]],
) -> dict[str, Any]:
    if source is not None and not isinstance(source, Mapping):
        path = Path(source).expanduser()
        if not path.exists():
            _record_input_error(
                findings,
                "invalid_taxonomy_manifest",
                "Explicit taxonomy manifest does not exist.",
                path,
            )
        else:
            try:
                value = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, json.JSONDecodeError):
                value = None
            if not isinstance(value, Mapping):
                _record_input_error(
                    findings,
                    "invalid_taxonomy_manifest",
                    "Explicit taxonomy manifest is not valid JSON object data.",
                    path,
                )
    return _load_taxonomy(source)


def _record_input_error(
    findings: list[dict[str, Any]],
    code: str,
    message: str,
    source: str | Path,
) -> None:
    _add_finding(findings, "error", code, message, source=str(source))


def _metadata_value(row: pd.Series, key: str) -> str | None:
    value = row.get("metadata")
    if isinstance(value, Mapping):
        return _text(value.get(key)) or None
    if isinstance(value, str) and value.strip():
        try:
            parsed = json.loads(value)
        except json.JSONDecodeError:
            return None
        if isinstance(parsed, Mapping):
            return _text(parsed.get(key)) or None
    return None


def _taxonomy_label_maps(
    frame: pd.DataFrame,
    taxonomy: Mapping[str, Any],
) -> tuple[dict[str, str], dict[str, str]]:
    category_labels = dict(taxonomy.get("category_labels", {}))
    subcategory_labels = dict(taxonomy.get("subcategory_labels", {}))
    for _, row in frame.iterrows():
        category = _text(row.get("category_id"))
        subcategory = _text(row.get("subcategory_id"))
        if category:
            category_labels.setdefault(
                category, _text(row.get("category_label"), category)
            )
            category_labels.setdefault(
                category, _metadata_value(row, "category") or category
            )
        if subcategory:
            subcategory_labels.setdefault(
                subcategory,
                _text(row.get("subcategory_label"), subcategory),
            )
            subcategory_labels.setdefault(
                subcategory,
                _metadata_value(row, "subcategory") or subcategory,
            )
    return category_labels, subcategory_labels


def _ordered_values(
    frame: pd.DataFrame,
    column: str,
    preferred: Iterable[Any] = (),
) -> list[Any]:
    values = [key[0] for key in _unique_keys(frame, (column,)) if key[0] is not None]
    output: list[Any] = []
    for value in list(preferred) + values:
        if value is not None and value not in output:
            output.append(value)
    return output


def _taxonomy_subcategory_keys(
    frame: pd.DataFrame,
    taxonomy: Mapping[str, Any],
) -> list[tuple[str, str]]:
    keys = list(taxonomy.get("subcategories", []))
    observed = [
        (key[0], key[1])
        for key in _unique_keys(frame, ("category_id", "subcategory_id"))
        if key[0] is not None and key[1] is not None
    ]
    for key in observed:
        if key not in keys:
            keys.append(key)
    return keys


def _heatmap_axis_label(
    key: tuple[Any, ...],
    dimensions: Sequence[str],
    category_labels: Mapping[str, str],
    subcategory_labels: Mapping[str, str],
) -> str:
    if dimensions == ("attacker_key",):
        return _text(key[0], "missing metadata")
    if dimensions == ("attacker_model",):
        return _display_model_name(key[0])
    if dimensions == ("category_id",):
        return category_labels.get(_text(key[0]), _text(key[0], "missing metadata"))
    if dimensions == ("subcategory_id",):
        subcategory = _text(key[0], "missing metadata")
        return f"{subcategory}: {_truncate_label(subcategory_labels.get(subcategory, subcategory), 36)}"
    if dimensions == ("attack",):
        return _text(key[0], "missing metadata")
    if dimensions == ("category_id", "subcategory_id"):
        category = _text(key[0], "?")
        subcategory = _text(key[1], "missing metadata")
        label = _truncate_label(subcategory_labels.get(subcategory, subcategory), 34)
        return f"{category} | {subcategory}: {label}"
    return " / ".join(_text(value, "missing metadata") for value in key)


def _heatmap_text_color(cmap: Any, value: float) -> tuple[str, Any]:
    rgba = cmap(float(value))
    red, green, blue = rgba[:3]
    luminance = 0.2126 * red + 0.7152 * green + 0.0722 * blue
    color = "white" if luminance < 0.52 else "black"
    effects = None
    if 0.42 <= luminance <= 0.62:
        effects = [
            withStroke(
                linewidth=1.5, foreground="black" if color == "white" else "white"
            )
        ]
    return color, effects


def _render_asr_heatmap(
    summary: pd.DataFrame,
    row_dimensions: Sequence[str],
    row_keys: Sequence[tuple[Any, ...]],
    column_dimensions: Sequence[str],
    column_keys: Sequence[tuple[Any, ...]],
    category_labels: Mapping[str, str],
    subcategory_labels: Mapping[str, str],
    path: Path,
    title: str,
    findings: list[dict[str, Any]],
    *,
    category_boundaries: Sequence[int] = (),
) -> None:
    status = "Judge validated: no"
    if not row_keys or not column_keys:
        _record_omission(
            path,
            title,
            "No taxonomy or attacker dimensions are available.",
            findings,
            "plot_omitted_asr_heatmap",
            status=status,
        )
        return
    lookup: dict[tuple[Any, ...], pd.Series] = {}
    for _, row in summary.iterrows():
        row_key = tuple(
            None
            if _is_missing(row.get(column))
            else str(_python_value(row.get(column)))
            for column in row_dimensions
        )
        column_key = tuple(
            None
            if _is_missing(row.get(column))
            else str(_python_value(row.get(column)))
            for column in column_dimensions
        )
        lookup[(*row_key, *column_key)] = row
    values = np.full((len(row_keys), len(column_keys)), np.nan)
    annotations: dict[tuple[int, int], str] = {}
    for row_index, row_key in enumerate(row_keys):
        for column_index, column_key in enumerate(column_keys):
            row = lookup.get((*row_key, *column_key))
            if row is None or _is_missing(row.get("automated_asr")):
                annotations[(row_index, column_index)] = (
                    "n/a" if row is None else "n/a\n" + _asr_annotation(row)
                )
                continue
            value = float(row["automated_asr"])
            values[row_index, column_index] = value
            annotations[(row_index, column_index)] = (
                f"{value:.0%}\n{_asr_annotation(row)}"
            )
    figure, axis = plt.subplots(
        figsize=(
            max(8.5, 1.9 * len(column_keys)),
            max(5.5, 0.55 * len(row_keys) + 1.8),
        ),
    )
    cmap = plt.get_cmap("viridis").copy()
    cmap.set_bad("#bdbdbd")
    image = axis.imshow(
        np.ma.masked_invalid(values), vmin=0, vmax=1, cmap=cmap, aspect="auto"
    )
    axis.set_xticks(
        range(len(column_keys)),
        labels=[
            _heatmap_axis_label(
                key, column_dimensions, category_labels, subcategory_labels
            )
            for key in column_keys
        ],
        rotation=30,
        ha="right",
    )
    axis.set_yticks(
        range(len(row_keys)),
        labels=[
            _heatmap_axis_label(
                key, row_dimensions, category_labels, subcategory_labels
            )
            for key in row_keys
        ],
    )
    axis.set_xlabel(" / ".join(column_dimensions))
    axis.set_ylabel(" / ".join(row_dimensions))
    axis.set_title(
        _title_with_n(
            title,
            "n = evaluated goals in each heatmap cell; S/F = successful/failed goals",
        ),
        fontsize=11,
    )
    axis.set_xticks(np.arange(-0.5, len(column_keys), 1), minor=True)
    axis.set_yticks(np.arange(-0.5, len(row_keys), 1), minor=True)
    axis.grid(which="minor", color="white", linewidth=0.8)
    axis.tick_params(which="minor", bottom=False, left=False)
    image_colorbar = figure.colorbar(image, ax=axis, ticks=[0, 0.25, 0.5, 0.75, 1])
    image_colorbar.set_ticklabels(["0%", "25%", "50%", "75%", "100%"])
    image_colorbar.set_label("ASR_goal")
    for boundary in category_boundaries:
        axis.axhline(boundary - 0.5, color="white", linewidth=2.2)
    for (row_index, column_index), annotation in annotations.items():
        if values[row_index, column_index] != values[row_index, column_index]:
            axis.text(
                column_index,
                row_index,
                annotation,
                ha="center",
                va="center",
                fontsize=7,
                color="black",
            )
        else:
            color, effects = _heatmap_text_color(cmap, values[row_index, column_index])
            axis.text(
                column_index,
                row_index,
                annotation,
                ha="center",
                va="center",
                fontsize=7 if len(row_keys) > 12 else 8,
                color=color,
                path_effects=effects,
            )
    _add_asr_definition(figure)
    _add_status_footer(figure, status)
    figure.subplots_adjust(
        left=0.28 if len(row_keys) > 12 else 0.20,
        right=0.90,
        bottom=0.18,
        top=0.91,
    )
    _save_figure(figure, path)


