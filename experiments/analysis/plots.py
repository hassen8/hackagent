def _target_call_summary(
    frame: pd.DataFrame,
    dimensions: Sequence[str],
    expected_keys: Iterable[Sequence[Any]] = (),
) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    keys = list(
        dict.fromkeys(
            _unique_keys(frame, dimensions) + [tuple(key) for key in expected_keys]
        )
    )
    for key in keys:
        subset = _subset_for_key(frame, dimensions, key)
        status = subset["evaluation_status"]
        calls = pd.to_numeric(subset["goal_target_call_count"], errors="coerce")
        missing = int(calls.isna().sum())
        target_calls = int(calls.sum()) if missing == 0 and not subset.empty else None
        success = int(status.eq("SUCCESSFUL_JAILBREAK").sum())
        failure = int(status.eq("FAILED_JAILBREAK").sum())
        evaluated = success + failure
        reason = ""
        if missing:
            reason = "missing target-call evidence"
        elif target_calls is None or target_calls <= 0:
            reason = "unavailable"
        rows.append(
            {
                **dict(zip(dimensions, key)),
                "goal_row_count": len(subset),
                "evaluated_count": evaluated,
                "success_count": success,
                "failure_count": failure,
                "target_call_count": target_calls,
                "target_call_evidence_missing_count": missing,
                "asr_target_call": success / target_calls
                if target_calls is not None and target_calls > 0
                else None,
                "unavailable_reason": reason,
            }
        )
    return pd.DataFrame(rows)


def _target_call_annotation(row: pd.Series) -> str:
    calls = row.get("target_call_count")
    calls_text = "n/a" if _is_missing(calls) else str(int(calls))
    annotation = (
        f"n={int(row.get('evaluated_count', 0))}\n"
        f"S/F={int(row.get('success_count', 0))}/{int(row.get('failure_count', 0))}\n"
        f"calls={calls_text}"
    )
    reason = _text(row.get("unavailable_reason"))
    return annotation + (f"\n{reason}" if reason else "")


def _render_target_call_bars(
    summary: pd.DataFrame,
    axis_keys: Sequence[tuple[Any, ...]],
    dimensions: Sequence[str],
    path: Path,
    title: str,
    taxonomy: Mapping[str, Any],
    color: str,
    findings: list[dict[str, Any]],
) -> None:
    status = "Judge validated: no"
    if not axis_keys:
        _record_omission(
            path,
            title,
            "No attacker-driven selected goal rows are available.",
            findings,
            "plot_omitted_target_call",
            status=status,
        )
        return
    lookup = {
        tuple(
            None
            if _is_missing(row.get(column))
            else str(_python_value(row.get(column)))
            for column in dimensions
        ): row
        for _, row in summary.iterrows()
    }
    labels: list[str] = []
    for key in axis_keys:
        if dimensions == ("attacker_key",):
            labels.append(_text(key[0], "missing metadata"))
        elif dimensions == ("attacker_model",):
            labels.append(_display_model_name(key[0]))
        elif dimensions == ("category_id",):
            labels.append(
                taxonomy.get("category_labels", {}).get(str(key[0]), str(key[0]))
            )
        elif dimensions == ("subcategory_id",):
            subcategory = str(key[0])
            labels.append(
                f"{subcategory}: {_truncate_label(taxonomy.get('subcategory_labels', {}).get(subcategory, subcategory), 42)}"
            )
        else:
            labels.append(" / ".join(_text(value, "missing metadata") for value in key))
    figure, axis = plt.subplots(figsize=(10, max(4.5, 0.62 * len(axis_keys))))
    plotted = False
    for index, key in enumerate(axis_keys):
        row = lookup.get(tuple(None if value is None else str(value) for value in key))
        if row is None or _is_missing(row.get("asr_target_call")):
            annotation = "n/a\n" + (
                _target_call_annotation(row) if row is not None else "n/a"
            )
            axis.text(
                0.01, index, annotation, va="center", fontsize=7.5, color="#555555"
            )
            continue
        plotted = True
        value = float(row["asr_target_call"])
        axis.barh(index, value, color=color, alpha=0.9)
        annotation = f"{value:.2%}\n" + _target_call_annotation(row)
        if value >= 0.76:
            axis.text(
                max(0.02, value - 0.015),
                index,
                annotation,
                ha="right",
                va="center",
                fontsize=7.5,
                color="white",
            )
        else:
            axis.text(
                min(0.985, value + 0.012),
                index,
                annotation,
                ha="left",
                va="center",
                fontsize=7.5,
            )
    axis.set_yticks(
        range(len(labels)), labels=[_truncate_label(label, 52) for label in labels]
    )
    axis.invert_yaxis()
    axis.set_xlim(0, 1.0)
    axis.set_xlabel("ASR_target_call")
    axis.set_title(
        _title_with_n(
            title,
            "n = evaluated goals in each group; calls = summed known target-model calls",
        ),
        fontsize=11,
    )
    axis.grid(axis="x", alpha=0.25)
    _add_asr_definition(figure, target_call=True)
    _add_status_footer(figure, status)
    figure.subplots_adjust(left=0.30, right=0.98, bottom=0.16, top=0.91)
    _save_figure(figure, path)
    if not plotted:
        _add_finding(
            findings,
            "warning",
            "plot_unavailable_target_call",
            "No target-call group has a recoverable strict ASR_target_call.",
            source=str(path),
        )


