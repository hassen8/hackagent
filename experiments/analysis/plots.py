def _is_missing(value: Any) -> bool:
    if value is None or value is pd.NA:
        return True
    if isinstance(value, float):
        return math.isnan(value)
    if isinstance(value, (list, dict, tuple)):
        return False
    try:
        return bool(pd.isna(value))
    except (TypeError, ValueError):
        return False


def _python_value(value: Any) -> Any:
    if _is_missing(value):
        return None
    if hasattr(value, "item") and not isinstance(value, (str, bytes)):
        try:
            return value.item()
        except (ValueError, TypeError):
            pass
    return value


def _text(value: Any, fallback: str = "") -> str:
    value = _python_value(value)
    return fallback if value is None else str(value).strip()


def _json_value(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), default=str)


def _display_model_name(value: Any) -> str:
    model = _text(value)
    return model.rsplit("/", 1)[-1] if model else "missing metadata"


def _add_finding(
    findings: list[dict[str, Any]],
    severity: str,
    code: str,
    message: str,
    count: int = 1,
    identifiers: Iterable[Any] = (),
    source: str = "plots",
) -> None:
    if count <= 0:
        return
    findings.append(
        {
            "severity": severity,
            "code": code,
            "message": message,
            "count": int(count),
            "representative_ids": _json_value(
                [
                    str(value)
                    for value in identifiers
                    if not _is_missing(value) and str(value).strip()
                ][:5]
            ),
            "source": source,
        }
    )


