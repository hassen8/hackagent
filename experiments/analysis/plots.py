def _time_till_jailbreak_summary(
    frame: pd.DataFrame,
    dimensions: Sequence[str],
    expected_keys: Iterable[Sequence[Any]] = (),
) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    keys = list(
        dict.fromkeys(
            _unique_keys(frame, dimensions)
            + [tuple(key) for key in expected_keys]
        )
    )
    for key in keys:
        subset = _subset_for_key(frame, dimensions, key)
        elapsed = pd.to_numeric(subset["goal_elapsed_s"], errors="coerce")
        valid = elapsed.notna() & np.isfinite(elapsed) & elapsed.gt(0)
        values = elapsed[valid]
        rows.append(
            {
                **dict(zip(dimensions, key)),
                "successful_goal_count": int(len(subset)),
                "known_time_count": int(valid.sum()),
                "missing_time_count": int((~valid).sum()),
                "mean_time_s": float(values.mean()) if not values.empty else None,
            }
        )
    return pd.DataFrame(rows)


