def _plot_target_token_asr_by_bin(
    data: PlotData,
    plots_dir: Path,
    findings: list[dict[str, Any]],
) -> None:
    path = plots_dir / PLOT_FILENAMES["target_token_asr_by_bin"]
    frame = _target_token_rows(data)
    if frame.empty:
        _record_omission(
            path,
            "ASR by target-token bin",
            "No target prompt and completion counts are available.",
            findings,
            "plot_omitted_target_token_asr",
            status="Judge validated: no",
        )
        return
    evaluated = frame[
        frame["evaluation_status"].isin(
            ["SUCCESSFUL_JAILBREAK", "FAILED_JAILBREAK"]
        )
    ].copy()
    if evaluated.empty:
        _record_omission(
            path,
            "ASR by target-token bin",
            "No evaluated goals have both target prompt and completion counts.",
            findings,
            "plot_omitted_target_token_asr",
            status="Judge validated: no",
        )
        return

    edges = [0, 256, 512, 1024, 2048, 4096, 8192, float("inf")]
    labels = [
        "0-255",
        "256-511",
        "512-1023",
        "1024-2047",
        "2048-4095",
        "4096-8191",
        "8192+",
    ]
    evaluated["_token_bin"] = pd.cut(
        evaluated["_target_total_tokens"],
        bins=edges,
        labels=labels,
        right=False,
        include_lowest=True,
    )
    rows: list[dict[str, Any]] = []
    for label in labels:
        subset = evaluated[evaluated["_token_bin"].astype("string").eq(label)]
        successes = int(subset["evaluation_status"].eq("SUCCESSFUL_JAILBREAK").sum())
        failures = int(subset["evaluation_status"].eq("FAILED_JAILBREAK").sum())
        n = successes + failures
        rows.append(
            {
                "label": label,
                "n": n,
                "successes": successes,
                "failures": failures,
                "asr": successes / n if n else None,
            }
        )
    summary = pd.DataFrame(rows)
    available = summary[summary["asr"].notna()]
    if available.empty:
        _record_omission(
            path,
            "ASR by target-token bin",
            "No target-token bin contains both evaluated success and failure data.",
            findings,
            "plot_omitted_target_token_asr",
            status="Judge validated: no",
        )
        return

    figure, axis = plt.subplots(figsize=(10, 5.5))
    bars = axis.bar(
        available["label"], available["asr"], color="#3182bd", alpha=0.9
    )
    for bar, (_, row) in zip(bars, available.iterrows()):
        axis.text(
            bar.get_x() + bar.get_width() / 2,
            float(row["asr"]),
            f"{float(row['asr']):.0%}\nn={int(row['n'])}\nS/F={int(row['successes'])}/{int(row['failures'])}",
            ha="center",
            va="bottom",
            fontsize=7,
        )
    axis.set_ylim(0, 1.08)
    axis.set_xlabel("Target-token bin")
    axis.set_ylabel("Attack-time ASR")
    axis.set_title(
        _title_with_n(
            "Attack-time ASR by target-token bin",
            "n = evaluated goals with target prompt and completion counts in each bin; S/F = successful/failed",
        ),
        fontsize=11,
    )
    axis.grid(axis="y", alpha=0.25)
    _add_asr_definition(figure)
    _add_token_estimate_note(figure)
    _add_status_footer(figure, "Judge validated: no")
    figure.subplots_adjust(bottom=0.18)
    _save_figure(figure, path)


