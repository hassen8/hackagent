def _target_token_rows(data: PlotData) -> pd.DataFrame:
    """Return target token rows with both prompt and completion counts.

    Partial rows can still have prompt and completion counts.
    They are useful for diagnostics, but their sum is not a complete total
    when calls or context are missing. AdvPrefix completion rows are included
    with that limitation rather than being silently dropped.
    """
    selected = _filter_attacks(
        _filter_applicability(data.selected_results, "driven")
    ).copy()
    required = {
        "goal_target_prompt_tokens_estimated",
        "goal_target_completion_tokens_estimated",
        "goal_token_evidence_status",
    }
    if not required.issubset(selected.columns):
        return selected.iloc[0:0].copy()
    selected["_target_prompt_tokens"] = pd.to_numeric(
        selected["goal_target_prompt_tokens_estimated"], errors="coerce"
    )
    selected["_target_completion_tokens"] = pd.to_numeric(
        selected["goal_target_completion_tokens_estimated"], errors="coerce"
    )
    status = selected["goal_token_evidence_status"].astype("string")
    numeric_components = (
        status.isin(("estimated", "partial"))
        & selected["_target_prompt_tokens"].notna()
        & selected["_target_completion_tokens"].notna()
        & np.isfinite(selected["_target_prompt_tokens"])
        & np.isfinite(selected["_target_completion_tokens"])
        & selected["_target_prompt_tokens"].ge(0)
        & selected["_target_completion_tokens"].ge(0)
    )
    selected["_token_evidence_status"] = status
    selected["_target_total_tokens"] = (
        selected["_target_prompt_tokens"] + selected["_target_completion_tokens"]
    )
    return selected[numeric_components].copy()


def _token_estimate_summary(data: PlotData) -> dict[str, Any]:
    selected = _filter_attacks(
        _filter_applicability(data.selected_results, "driven")
    )
    if "goal_token_evidence_status" not in selected:
        return {
            "available": False,
            "goal_rows": int(len(selected)),
            "estimated_goal_rows": 0,
            "partial_goal_rows": 0,
            "missing_goal_rows": 0,
            "complete_target_token_goal_rows": 0,
            "partial_target_token_goal_rows": 0,
            "target_token_goal_rows": 0,
            "excluded_goal_rows": int(len(selected)),
        }
    status = selected["goal_token_evidence_status"].astype("string")
    prompt = pd.to_numeric(
        selected.get("goal_target_prompt_tokens_estimated", pd.Series(dtype=float)),
        errors="coerce",
    )
    completion = pd.to_numeric(
        selected.get("goal_target_completion_tokens_estimated", pd.Series(dtype=float)),
        errors="coerce",
    )
    numeric_components = (
        status.isin(("estimated", "partial"))
        & prompt.notna()
        & completion.notna()
        & np.isfinite(prompt)
        & np.isfinite(completion)
        & prompt.ge(0)
        & completion.ge(0)
    )
    complete = numeric_components & status.eq("estimated")
    partial_numeric = numeric_components & status.eq("partial")
    proxy_rows = _target_token_rows(data)
    by_attack: dict[str, dict[str, int]] = {}
    for attack, group in selected.groupby("attack", dropna=False, sort=False):
        attack_label = _text(attack, "missing metadata")
        proxy_group = proxy_rows[
            proxy_rows["attack"].astype("string").eq(str(attack))
        ]
        by_attack[attack_label] = {
            "goal_rows": int(len(group)),
            "complete_target_token_goal_rows": int(
                proxy_group["_token_evidence_status"].eq("estimated").sum()
            ),
            "partial_target_token_goal_rows": int(
                proxy_group["_token_evidence_status"].eq("partial").sum()
            ),
            "target_token_goal_rows": int(len(proxy_group)),
            "excluded_goal_rows": int(len(group) - len(proxy_group)),
        }
    estimated = int(status.eq("estimated").sum())
    partial = int(status.eq("partial").sum())
    missing = int(status.eq("missing").sum())
    return {
        "available": bool(len(selected)),
        "goal_rows": int(len(selected)),
        "estimated_goal_rows": estimated,
        "partial_goal_rows": partial,
        "missing_goal_rows": missing,
        "complete_target_token_goal_rows": int(complete.sum()),
        "partial_target_token_goal_rows": int(partial_numeric.sum()),
        "target_token_goal_rows": int(numeric_components.sum()),
        "excluded_goal_rows": int(len(selected) - numeric_components.sum()),
        "by_attack": by_attack,
    }


