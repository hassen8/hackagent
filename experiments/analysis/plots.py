def _consensus_category(row: pd.Series, column: str) -> str:
    consensus = _parse_json_object(row.get(column))
    decision = consensus.get("decision") if consensus else None
    if decision == "SUCCESSFUL_JAILBREAK":
        return "successful consensus"
    if decision == "FAILED_JAILBREAK":
        return "failed consensus"
    return "no majority"


