def prepare_plot_data(runs: pd.DataFrame, results: pd.DataFrame) -> PlotData:
    """Select repetition-one canonical completed attempts for comparisons."""
    normalized_runs = _normalize_plot_frame(runs)
    normalized_results = _normalize_plot_frame(results)
    repetition_one_runs = normalized_runs[normalized_runs["repetition"].eq(1)].copy()
    completed = repetition_one_runs[repetition_one_runs["status"].eq("completed")]
    if (
        "goal_evidence_complete" in completed
        and completed["goal_evidence_complete"].notna().any()
    ):
        completed = completed[
            completed["goal_evidence_complete"].isna()
            | completed["goal_evidence_complete"].eq(True)
        ]
    if completed.empty:
        selected_runs = completed.copy()
    else:
        selected_runs = (
            completed.groupby(
                list(CANONICAL_CELL_COLUMNS),
                dropna=False,
                sort=False,
                observed=False,
            )
            .tail(1)
            .copy()
        )
    selected_run_ids = set(selected_runs[RUN_ID_COLUMN].dropna().astype(str))
    selected_results = normalized_results[
        normalized_results[RUN_ID_COLUMN].astype("string").isin(selected_run_ids)
        & normalized_results["repetition"].eq(1)
    ].copy()
    return PlotData(
        runs=normalized_runs,
        results=normalized_results,
        repetition_one_runs=repetition_one_runs,
        selected_runs=selected_runs,
        selected_results=selected_results,
        duplicate_completed_attempts=max(0, len(completed) - len(selected_runs)),
    )


