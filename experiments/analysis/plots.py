def _empty_asr_counts() -> dict[str, Any]:
    return {
        "goal_row_count": 0,
        "evaluated_count": 0,
        "success_count": 0,
        "failure_count": 0,
        "not_evaluated_count": 0,
        "automated_asr": None,
    }


def _asr_counts(frame: pd.DataFrame) -> dict[str, Any]:
    status = frame["evaluation_status"]
    success = int(status.eq("SUCCESSFUL_JAILBREAK").sum())
    failure = int(status.eq("FAILED_JAILBREAK").sum())
    not_evaluated = int(status.eq("NOT_EVALUATED").sum())
    evaluated = success + failure
    return {
        "goal_row_count": int(len(frame)),
        "evaluated_count": evaluated,
        "success_count": success,
        "failure_count": failure,
        "not_evaluated_count": not_evaluated,
        "automated_asr": success / evaluated if evaluated else None,
    }


def _run_counts_by_key(
    frame: pd.DataFrame, dimensions: Sequence[str]
) -> dict[tuple[Any, ...], int]:
    return {key: len(group) for key, group in _groups_by_key(frame, dimensions)}


def _candidate_statuses(
    frame: pd.DataFrame,
    dimensions: Sequence[str],
) -> dict[tuple[Any, ...], set[str]]:
    return {
        key: {str(value) for value in group["status"].dropna()}
        for key, group in _groups_by_key(frame, dimensions)
    }


def _asr_summary(
    data: PlotData,
    applicability: str,
    dimensions: Sequence[str],
    expected_keys: Iterable[Sequence[Any]] = (),
) -> pd.DataFrame:
    candidates = _filter_attacks(
        _filter_applicability(data.repetition_one_runs, applicability)
    )
    selected_runs = _filter_attacks(
        _filter_applicability(data.selected_runs, applicability)
    )
    selected_results = _filter_attacks(
        _filter_applicability(data.selected_results, applicability)
    )
    keys = list(
        dict.fromkeys(
            _unique_keys(candidates, dimensions)
            + _unique_keys(selected_results, dimensions)
            + [tuple(key) for key in expected_keys]
        )
    )
    selected_run_counts = _run_counts_by_key(selected_runs, dimensions)
    statuses = _candidate_statuses(candidates, dimensions)
    rows: list[dict[str, Any]] = []
    for key in keys:
        subset = _subset_for_key(selected_results, dimensions, key)
        counts = _asr_counts(subset) if not subset.empty else _empty_asr_counts()
        reason = ""
        if counts["goal_row_count"] == 0:
            reason = (
                "blocked" if "blocked" in statuses.get(key, set()) else "unavailable"
            )
        row = {dimension: value for dimension, value in zip(dimensions, key)}
        row.update(counts)
        row["selected_run_count"] = selected_run_counts.get(key, 0)
        row["unavailable_reason"] = reason
        rows.append(row)
    return pd.DataFrame(rows)


def _asr_annotation(row: pd.Series) -> str:
    annotation = (
        f"n={int(row.get('evaluated_count', 0))}\n"
        f"S/F={int(row.get('success_count', 0))}/{int(row.get('failure_count', 0))}"
    )
    reason = _text(row.get("unavailable_reason"))
    return annotation + (f"\n{reason}" if reason else "")


