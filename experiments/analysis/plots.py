def _target_call_mean_summary(
    frame: pd.DataFrame,
    dimensions: Sequence[str],
    expected_keys: Iterable[Sequence[Any]] = (),
) -> pd.DataFrame:
    evaluated = frame[
        frame["evaluation_status"].isin(
            ["SUCCESSFUL_JAILBREAK", "FAILED_JAILBREAK"]
        )
    ]
    rows: list[dict[str, Any]] = []
    keys = list(
        dict.fromkeys(
            _unique_keys(evaluated, dimensions)
            + [tuple(key) for key in expected_keys]
        )
    )
    for key in keys:
        subset = _subset_for_key(evaluated, dimensions, key)
        calls = pd.to_numeric(subset["goal_target_call_count"], errors="coerce")
        valid = calls.notna() & np.isfinite(calls) & calls.ge(0)
        valid_calls = calls[valid]
        rows.append(
            {
                **dict(zip(dimensions, key)),
                "evaluated_count": int(len(subset)),
                "known_call_count": int(valid.sum()),
                "missing_call_count": int((~valid).sum()),
                "mean_target_calls": (
                    float(valid_calls.mean()) if not valid_calls.empty else None
                ),
            }
        )
    return pd.DataFrame(rows)


