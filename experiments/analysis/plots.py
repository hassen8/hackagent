def _ensure_columns(
    frame: pd.DataFrame,
    columns: Iterable[str],
) -> pd.DataFrame:
    result = frame.copy()
    for column in columns:
        if column not in result:
            result[column] = pd.NA
    return result


def _canonical_key(row: pd.Series, columns: Sequence[str]) -> tuple[Any, ...]:
    return tuple(
        None
        if column not in row or _is_missing(row[column])
        else str(_python_value(row[column]))
        for column in columns
    )


def _unique_keys(frame: pd.DataFrame, columns: Sequence[str]) -> list[tuple[Any, ...]]:
    if frame.empty:
        return []
    keys: list[tuple[Any, ...]] = []
    seen: set[tuple[Any, ...]] = set()
    for _, row in frame.iterrows():
        key = _canonical_key(row, columns)
        if key not in seen:
            seen.add(key)
            keys.append(key)
    return keys


def _groups_by_key(
    frame: pd.DataFrame,
    dimensions: Sequence[str],
) -> Iterable[tuple[tuple[Any, ...], pd.DataFrame]]:
    if frame.empty:
        return []
    groups: dict[tuple[Any, ...], list[Any]] = {}
    for index, row in frame.iterrows():
        groups.setdefault(_canonical_key(row, dimensions), []).append(index)
    return ((key, frame.loc[indexes]) for key, indexes in groups.items())


def _subset_for_key(
    frame: pd.DataFrame,
    dimensions: Sequence[str],
    key: Sequence[Any],
) -> pd.DataFrame:
    subset = frame
    for column, value in zip(dimensions, key):
        if value is None:
            subset = subset[subset[column].isna()]
        else:
            subset = subset[subset[column].astype("string").eq(str(value))]
    return subset


def _filter_applicability(frame: pd.DataFrame, applicability: str) -> pd.DataFrame:
    if "attacker_applicability" not in frame:
        return frame.iloc[0:0].copy()
    return frame[frame["attacker_applicability"].astype("string").eq(applicability)]


def _filter_attacks(frame: pd.DataFrame) -> pd.DataFrame:
    if "attack" not in frame:
        return frame.iloc[0:0].copy()
    frame = frame[frame["attack"].isin(ATTACKS)]
    if _EXCLUDED_ATTACKS and "attack" in frame:
        frame = frame[~frame["attack"].astype("string").isin(_EXCLUDED_ATTACKS)]
    return frame


def _outside_legend(
    axis: Any, *args: Any, title: str = "Attack", fontsize: int = 8, **kwargs: Any
) -> Any:
    """Place a legend outside the axes so it never covers plotted content."""
    legend = axis.legend(*args, title=title, fontsize=fontsize,
                         loc="upper left", bbox_to_anchor=(1.01, 1.0), **kwargs)
    axis.figure.subplots_adjust(right=0.84)
    return legend


def _attacker_exclusion_mask(frame: pd.DataFrame, excluded: set[str]) -> pd.Series:
    if not excluded:
        return pd.Series(True, index=frame.index)
    key = frame.get("attacker_key", pd.Series("", index=frame.index)).astype("string")
    model = frame.get("attacker_model", pd.Series("", index=frame.index)).astype("string")
    return ~key.isin(excluded) & ~model.isin(excluded)


def _filter_excluded_attackers(
    frame: pd.DataFrame, excluded: set[str]
) -> pd.DataFrame:
    return frame[_attacker_exclusion_mask(frame, excluded)]


def _filter_attacker_metadata(
    source: Mapping[str, Any] | None, excluded: set[str]
) -> Mapping[str, Any] | None:
    """Remove excluded attacker identities from expected/coverage metadata."""
    if source is None or not excluded:
        return source
    filtered = dict(source)
    for key in ("cells",):
        values = source.get(key)
        if isinstance(values, list):
            filtered[key] = [
                cell
                for cell in values
                if isinstance(cell, Mapping)
                and bool(_attacker_exclusion_mask(pd.DataFrame([cell]), excluded).iloc[0])
            ]
    for key in ("attacker_keys",):
        values = source.get(key)
        if isinstance(values, list):
            filtered[key] = [value for value in values if str(value) not in excluded]
    models = source.get("attacker_models")
    if isinstance(models, Mapping):
        filtered["attacker_models"] = {
            key: value
            for key, value in models.items()
            if str(key) not in excluded and str(value) not in excluded
        }
    cells = filtered.get("cells")
    if isinstance(cells, list):
        filtered["expected_cell_count"] = len(cells)
        goal_count = sum(
            len(cell.get("goal_ids") or [])
            for cell in cells
            if isinstance(cell, Mapping)
        )
        if goal_count:
            filtered["expected_goal_evaluation_count"] = goal_count
    return filtered


def _unique_values(values: Iterable[Any]) -> list[Any]:
    output: list[Any] = []
    for value in values:
        if value is None or _is_missing(value) or value in output:
            continue
        output.append(value)
    return output


def _plot_inventory(
    data: PlotData,
    taxonomy: Mapping[str, Any],
    expected_manifest: Mapping[str, Any] | None = None,
    coverage: Mapping[str, Any] | None = None,
    excluded_attackers: set[str] | None = None,
) -> dict[str, list[Any]]:
    """Build axis inventories from explicit expectations, then observations."""
    excluded_attackers = excluded_attackers or set()
    expected_cells = [
        cell
        for cell in (
        expected_manifest.get("cells", []) if expected_manifest is not None else []
        )
        if isinstance(cell, Mapping)
        and _attacker_exclusion_mask(
            pd.DataFrame([cell]), excluded_attackers
        ).iloc[0]
    ]
    if not expected_cells and coverage is not None:
        expected_cells = [
            cell
            for cell in coverage.get("cells", [])
            if isinstance(cell, Mapping)
            and _attacker_exclusion_mask(
                pd.DataFrame([cell]), excluded_attackers
            ).iloc[0]
        ]
    expected_attacker_keys: list[Any] = []
    filtered_expected_manifest = _filter_attacker_metadata(
        expected_manifest, excluded_attackers
    )
    declared_keys = (
        filtered_expected_manifest.get("attacker_keys", ())
        if filtered_expected_manifest
        else {}
    )
    if isinstance(declared_keys, (list, tuple)):
        expected_attacker_keys.extend(declared_keys)
    expected_attacker_keys.extend(
        cell.get("attacker_key")
        for cell in expected_cells
        if isinstance(cell, Mapping) and cell.get("attacker_key")
    )
    observed_driven = _filter_excluded_attackers(
        _filter_attacks(_filter_applicability(data.repetition_one_runs, "driven")),
        excluded_attackers,
    )
    attacker_keys = _unique_values(
        list(expected_attacker_keys)
        + _ordered_values(observed_driven, "attacker_key")
    )

    declared_attacks = expected_manifest.get("attacks", ()) if expected_manifest else ()
    attacks = _allowed_attacks(
        list(ATTACKS)
        + [attack for attack in declared_attacks if attack in ATTACKS]
        + [
            attack
            for attack in _ordered_values(observed_driven, "attack")
            if attack in ATTACKS
        ]
    )
    categories = _unique_values(
        list(taxonomy.get("categories", CATEGORIES))
        + [
            cell.get("category_id")
            for cell in expected_cells
            if isinstance(cell, Mapping)
        ]
        + _ordered_values(observed_driven, "category_id")
    )
    if not categories:
        categories = list(CATEGORIES)
    subcategories = list(taxonomy.get("subcategories", []))
    batch_map = taxonomy.get("batch_to_taxonomy", {})
    for cell in expected_cells:
        if not isinstance(cell, Mapping):
            continue
        category = _text(cell.get("category_id"))
        subcategory = _text(cell.get("subcategory_id"))
        if not category or not subcategory:
            category, subcategory = batch_map.get(
                _text(cell.get("goal_batch_id")), (None, None)
            )
        if category and subcategory and (category, subcategory) not in subcategories:
            subcategories.append((category, subcategory))
    for key in _unique_keys(observed_driven, ("category_id", "subcategory_id")):
        if key[0] is not None and key[1] is not None and key not in subcategories:
            subcategories.append((key[0], key[1]))
    return {
        "attacker_keys": attacker_keys,
        "attacks": attacks,
        "categories": categories,
        "subcategories": subcategories,
    }


